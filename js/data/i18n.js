export function localize(value, language = 'de') {
  if (value == null) return '';
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  return value[language] ?? value.de ?? value.en ?? '';
}

export function ui(key, language = 'de') {
  return localize(UI_TEXT[key] ?? key, language);
}

export function formatDate(timestamp, language = 'de') {
  return new Intl.DateTimeFormat(language === 'de' ? 'de-DE' : 'en-GB', {
    dateStyle: 'medium',
    timeStyle: 'short'
  }).format(new Date(timestamp));
}

export function formatDuration(seconds) {
  const numeric = Number.isFinite(Number(seconds)) ? Number(seconds) : 0;
  const sign = numeric < 0 ? '−' : '';
  const safe = Math.ceil(Math.abs(numeric));
  const minutes = Math.floor(safe / 60);
  const rest = safe % 60;
  return `${sign}${String(minutes).padStart(2, '0')}:${String(rest).padStart(2, '0')}`;
}
